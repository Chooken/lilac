#!/usr/bin/perl
# Generates lib/Standard's numeric types (math plan phase 2): the ten
# integer files and three float files are this script's output, so change
# the script and rerun it (`perl scripts/numeric_types.pl lib/Standard`)
# rather than editing them by hand.
use strict;
use warnings;

my $out = shift or die "usage: perl scripts/numeric_types.pl lib/Standard";
my $header = "// Generated by scripts/numeric_types.pl: edit that and rerun it.

";

# name, bits ('native' for pointer width), signed
my @ints = (
    ['Int8', 8, 1], ['Int16', 16, 1], ['Int32', 32, 1], ['Int64', 64, 1], ['Int', 'native', 1],
    ['Uint8', 8, 0], ['Uint16', 16, 0], ['Uint32', 32, 0], ['Uint64', 64, 0], ['Uint', 'native', 0],
);
# name, bits, significand bits (with the hidden one), largest finite
my @floats = (
    ['Float16', 16, 11, '65504.0'],
    ['Float32', 32, 24, undef],
    ['Float64', 64, 53, undef],
);

sub container { my ($b) = @_; $b eq 'native' ? '@bit_native' : "\@bit$b" }
sub minb { my ($b) = @_; $b eq 'native' ? 32 : $b }
sub maxb { my ($b) = @_; $b eq 'native' ? 64 : $b }
sub method_name { lc $_[0] }    # Int32 -> int32

# Whether every value of integer type $t is a value of integer type $u.
sub int_exact {
    my ($t, $u) = @_;
    return 0 if $t->[0] eq $u->[0];
    return 0 if $t->[2] && !$u->[2];
    return minb($u->[1]) > maxb($t->[1]) if !$t->[2] && $u->[2];
    return minb($u->[1]) >= maxb($t->[1]);
}

# Whether every value of integer type $t is a value of float type $f.
sub float_exact {
    my ($t, $f) = @_;
    return 0 if $t->[1] eq 'native';
    my $magnitude = $t->[2] ? $t->[1] - 1 : $t->[1];
    return $magnitude <= $f->[2];
}

# `expr` (an integer of bits $from, signed $signed) resized to bits $to.
sub resize {
    my ($expr, $from, $signed, $to) = @_;
    return $expr if $from eq $to;
    return ($signed ? '@extend_sign' : '@extend_zero') . "($expr)" if minb($to) >= maxb($from);
    return "\@truncate($expr)" if maxb($to) <= minb($from);
    die "no resize from $from to $to";
}

sub range_text {
    my ($t) = @_;
    my ($name, $bits, $signed) = @$t;
    if ($bits eq 'native') {
        return $signed
            ? "from -2^(w - 1) to 2^(w - 1) - 1 at the target's pointer width `w` (C's `ptrdiff_t`)"
            : "from 0 to 2^w - 1 at the target's pointer width `w` (C's `size_t`)";
    }
    return $signed ? "from -2^" . ($bits - 1) . " to 2^" . ($bits - 1) . " - 1"
                   : "from 0 to 2^$bits - 1";
}

sub hex_max {
    my ($bits, $signed) = @_;
    my $digits = $bits / 4;
    return '0x' . ($signed ? '7' . ('F' x ($digits - 1)) : 'F' x $digits);
}

sub int_file {
    my ($t) = @_;
    my ($name, $bits, $signed) = @$t;
    my $c = container($bits);
    my $s = $bits;                      # intrinsic suffix
    my $u = $signed ? '' : '_u';        # unsigned intrinsic infix
    my $helper = $signed ? '' : 'u_';   # helper infix
    my $kind = $signed ? 'signed' : 'unsigned';
    my $width = $bits eq 'native' ? 'pointer-width' : "$bits-bit";
    my $text = '';
    if ($name eq 'Uint8') {
        $text .= "/// A byte: an unsigned 8-bit integer.\nByte: alias Uint8\n\n";
    }
    $text .= "/// A $kind $width integer, " . range_text($t) . ".\n";
    $text .= "///\n/// " . ($signed ? "`+`, `-`, `*` and negation" : "`+`, `-` and `*`")
        . " panic on overflow in Debug builds and wrap in\n/// Release; the `wrapping_*` methods wrap in every mode. `/` and `%`\n/// panic on a zero divisor"
        . ($signed ? " and on `MIN / -1`" : "") . ".\n";
    $text .= "$name: object {\n\n    private {\n        data: $c\n    }\n\n";

    # Constants.
    if ($bits eq 'native') {
        if ($signed) {
            $text .= "    /// The largest `Int`: `2^(w - 1) - 1` (C's `PTRDIFF_MAX`).\n";
            $text .= "    MAX: Int => Int { data = \@bit_shift_right_u_native(\@bit_not_native(0x0), 0x1) }\n\n";
            $text .= "    /// The smallest `Int`: `-2^(w - 1)`.\n";
            $text .= "    MIN: Int => Int { data = \@bit_not_native(\@bit_shift_right_u_native(\@bit_not_native(0x0), 0x1)) }\n\n";
        } else {
            $text .= "    /// The largest `Uint`: `2^w - 1` (C's `SIZE_MAX`).\n";
            $text .= "    MAX: Uint => Uint { data = \@bit_not_native(0x0) }\n\n";
            $text .= "    /// The smallest `Uint`: 0.\n";
            $text .= "    MIN: Uint => Uint { data = 0x0 }\n\n";
        }
    } else {
        my $max = hex_max($bits, $signed);
        my $min = $signed ? '0x8' . ('0' x ($bits / 4 - 1)) : '0x0';
        my ($max_text, $min_text) = $signed
            ? ("2^" . ($bits - 1) . " - 1", "-2^" . ($bits - 1))
            : ("2^$bits - 1", "0");
        $text .= "    /// The largest `$name`: $max_text.\n    MAX: $name => $name { data = $max }\n\n";
        $text .= "    /// The smallest `$name`: $min_text.\n    MIN: $name => $name { data = $min }\n\n";
    }

    # Operators, for (T, T), (T, bits) and (bits, T).
    my %arith = (
        div => "\@i_div$u\_$s",
        mod => "\@i_mod$u\_$s",
    );
    my %checked = (add => 'add', sub => 'subtract', mul => 'multiply');
    my @compare = qw(less_than greater_than less_than_or_equal greater_than_or_equal);
    my @shapes = (
        [$name, $name, 'lhs.data', 'rhs.data'],
        [$name, $c, 'lhs.data', 'rhs'],
        [$c, $name, 'lhs', 'rhs.data'],
    );
    for my $i (0 .. $#shapes) {
        my ($l, $r, $a, $b) = @{$shapes[$i]};
        if ($i == 1) {
            $text .= "    // With a bit container on either side, so a literal operand\n"
                . "    // takes this type's width: `n * 2`, `1 < n`.\n";
        }
        for my $op (qw(add sub mul div mod)) {
            if (my $word = $checked{$op}) {
                $text .= "    \@$op: function (lhs: $l, rhs: $r) $name =>\n        $name { data = if \@builtin.Build.mode == .Debug and \@i_$op\_overflows$u\_$s($a, $b) then \@panic(\"attempt to $word with overflow\") else \@i_$op\_$s($a, $b) }\n";
            } else {
                $text .= "    \@$op: function (lhs: $l, rhs: $r) $name => $name { data = $arith{$op}($a, $b) }\n";
            }
        }
        $text .= "\n";
        for my $op (@compare) {
            $text .= "    \@$op: function (lhs: $l, rhs: $r) Bool => \@i_$op$u\_$s($a, $b)\n";
        }
        $text .= "\n";
        if ($i == 0 && $signed) {
            $text .= "    \@negate: function (value: $name) $name =>\n        $name { data = if \@builtin.Build.mode == .Debug and \@i_sub_overflows_$s(0x0, value.data) then \@panic(\"attempt to negate with overflow\") else \@i_negate_$s(value.data) }\n\n";
        }
    }

    # Wrapping arithmetic.
    for my $w (['add', 'self + other', 'add'], ['sub', 'self - other', 'subtract'], ['mul', 'self * other', 'multiply']) {
        my ($op, $what, $word) = @$w;
        $text .= "    /// `$what`, wrapping around at the type's range in every build mode.\n";
        $text .= "    wrapping_$word: function (self, other: $name) $name => $name { data = \@i_$op\_$s(self.data, other.data) }\n\n";
    }
    $text .= "    /// `-self`, wrapping around at the type's range in every build mode"
        . ($signed ? " (`MIN` stays `MIN`)" : " (`2^w - self`, 0 for 0)") . ".\n";
    $text .= "    wrapping_negate: function (self) $name => $name { data = \@i_negate_$s(self.data) }\n\n";

    # Conversions.
    $text .= "    \@conversion: function (from: $c) $name => $name { data = from }\n";
    $text .= "    \@conversion: function (from: $name) $c => from.data\n\n";
    my @exact_from = grep { int_exact($_, $t) } @ints;
    if (@exact_from) {
        $text .= "    // `as` from every integer type whose values all fit.\n";
        for my $f (@exact_from) {
            my $from = resize("from as " . container($f->[1]), $f->[1], $f->[2], $bits);
            $text .= "    \@conversion: function (from: $f->[0]) $name => $name { data = $from }\n";
        }
        $text .= "\n";
    }
    for my $v (grep { $_->[0] ne $name && !int_exact($t, $_) } @ints) {
        my ($vname, $vbits, $vsigned) = @$v;
        my $vc = container($vbits);
        my $m = method_name($vname);
        my $wrap = resize('self.data', $bits, $signed, $vbits);
        my $back = resize('bits', $vbits, $vsigned, $bits);
        my @cond = ("back == self.data");
        push @cond, "\@i_greater_than_or_equal_$s(self.data, 0x0)" if $signed && !$vsigned;
        push @cond, "\@i_greater_than_or_equal_$vbits(bits, 0x0)" if !$signed && $vsigned;
        $text .= "    /// This value as a" . ($vname =~ /^I/ ? "n" : "") . " `$vname`; fails when it is out of `$vname`'s range.\n";
        $text .= "    to_$m: function (self) value: $vname else nothing {\n";
        $text .= "        bits: $vc = $wrap\n";
        $text .= "        back: $c = $back\n";
        $text .= "        if " . join(' and ', @cond) . " {\n";
        $text .= "            value = bits\n            return\n        }\n        fail\n    }\n\n";
        $text .= "    /// This value as a" . ($vname =~ /^I/ ? "n" : "") . " `$vname`, wrapping around at `$vname`'s range: the\n";
        $text .= "    /// low bits" . (maxb($vbits) > minb($bits) ? ", " . ($signed ? "sign" : "zero") . "-extended" : "") . ".\n";
        $text .= "    to_$m\_wrapping: function (self) $vname => $wrap as $vc as $vname\n\n";
    }
    my $to_float = $signed ? '@int_to_float' : '@uint_to_float';
    for my $f (grep { !float_exact($t, $_) } @floats) {
        my ($fname, $fbits) = @$f;
        my $m = method_name($fname);
        $text .= "    /// This value as a `$fname`, rounded to the nearest (ties to even);\n";
        $text .= "    /// past `$fname`'s largest finite value it is an infinity.\n" if $fbits == 16;
        $text .= "    to_$m\_rounded: function (self) $fname => $to_float(self.data) as \@fbit$fbits as $fname\n\n";
    }

    # Formatting.
    if ($signed) {
        $text .= "    /// Signed decimal.\n    \@format: function (self, out: ref Formatter) nothing {\n";
        $text .= "        write_signed(out, " . ($bits eq '64' ? 'self.data' : '@extend_sign(self.data)') . ")\n    }\n\n";
    } else {
        $text .= "    /// Unsigned decimal.\n    \@format: function (self, out: ref Formatter) nothing {\n";
        $text .= "        write_unsigned(out, " . ($bits eq '64' ? 'self.data' : '@extend_zero(self.data)') . ", 0xA)\n    }\n\n";
    }
    my $bits64 = $bits eq '64' ? 'self.data' : '@extend_zero(self.data)';
    $text .= "    /// The bits in hexadecimal, at this type's width: `{n.hex()}`.\n";
    $text .= "    hex: function (self) Hex => Hex { value = $bits64 }\n\n";
    $text .= "    /// The bits in binary, at this type's width: `{n.binary()}`.\n";
    $text .= "    binary: function (self) Binary => Binary { value = $bits64 }\n}\n";
    return $text;
}

sub float_file {
    my ($f) = @_;
    my ($name, $bits, $p, $max) = @$f;
    my $c = "\@fbit$bits";
    my $s = $bits;
    my $ctype = { 16 => '`_Float16`', 32 => "C's `float`", 64 => "C's `double`" }->{$bits};
    my $text = "/// A $bits-bit IEEE 754 binary floating-point number ($ctype).\n";
    $text .= "///\n/// Arithmetic is IEEE's, rounded to nearest (ties to even); `%` is C's\n/// `fmod`. `==` compares bits: `0.0 == -0.0` is false.\n";
    $text .= "$name: object {\n\n    private {\n        data: $c\n    }\n\n";
    my @compare = qw(less_than greater_than less_than_or_equal greater_than_or_equal);
    my @shapes = (
        [$name, $name, 'lhs.data', 'rhs.data'],
        [$name, $c, 'lhs.data', 'rhs'],
        [$c, $name, 'lhs', 'rhs.data'],
    );
    for my $i (0 .. $#shapes) {
        my ($l, $r, $a, $b) = @{$shapes[$i]};
        if ($i == 1) {
            $text .= "    // With a float container on either side, so a literal operand\n"
                . "    // takes this type's width: `x * 2.0`, `1.0 < x`.\n";
        }
        for my $op (qw(add sub mul div mod)) {
            $text .= "    \@$op: function (lhs: $l, rhs: $r) $name => $name { data = \@f_$op\_$s($a, $b) }\n";
        }
        $text .= "\n";
        for my $op (@compare) {
            $text .= "    \@$op: function (lhs: $l, rhs: $r) Bool => \@f_$op\_$s($a, $b)\n";
        }
        $text .= "\n";
        if ($i == 0) {
            $text .= "    \@negate: function (value: $name) $name => $name { data = \@f_negate_$s(value.data) }\n\n";
        }
    }
    $text .= "    \@conversion: function (from: $c) $name => $name { data = from }\n";
    $text .= "    \@conversion: function (from: $name) $c => from.data\n\n";

    my @exact_floats = grep { $_->[1] < $bits } @floats;
    my @exact_ints = grep { float_exact($_, $f) } @ints;
    $text .= "    // `as` from every type whose values all fit.\n";
    for my $g (@exact_floats) {
        $text .= "    \@conversion: function (from: $g->[0]) $name => $name { data = \@float_convert(from as \@fbit$g->[1]) }\n";
    }
    for my $t (@exact_ints) {
        my $conv = $t->[2] ? '@int_to_float' : '@uint_to_float';
        $text .= "    \@conversion: function (from: $t->[0]) $name => $name { data = $conv(from as " . container($t->[1]) . ") }\n";
    }
    $text .= "\n";
    for my $g (grep { $_->[1] < $bits } @floats) {
        my $m = method_name($g->[0]);
        $text .= "    /// This value as a `$g->[0]`, rounded to the nearest (ties to even);\n";
        $text .= "    /// past `$g->[0]`'s largest finite value it is an infinity.\n";
        $text .= "    to_$m\_rounded: function (self) $g->[0] => \@float_convert(self.data) as \@fbit$g->[1] as $g->[0]\n\n";
    }
    for my $t (@ints) {
        my ($tname, $tbits, $tsigned) = @$t;
        my $m = method_name($tname);
        my $tc = container($tbits);
        my $conv = $tsigned ? '@float_to_int' : '@float_to_uint';
        my $an = $tname =~ /^I/ ? 'an' : 'a';
        $text .= "    /// This value as $an `$tname`, rounded toward zero; past `$tname`'s range\n";
        $text .= "    /// it is `$tname.MIN` or `$tname.MAX`, and NaN is 0.\n";
        $text .= "    to_$m\_truncated: function (self) $tname => $conv(self.data) as $tc as $tname\n\n";
        $text .= "    /// This value as $an `$tname`; fails on NaN, on an infinity, on a fraction\n";
        $text .= "    /// and out of `$tname`'s range.\n";
        $text .= "    to_$m: function (self) value: $tname else nothing {\n";
        if ($tbits eq 'native') {
            my $wide = $tsigned ? 'Int64' : 'Uint64';
            my $wm = method_name($wide);
            $text .= "        if self.to_$wm() -> wide: $wide {\n";
            $text .= "            if wide.to_$m() -> narrow: $tname {\n";
            $text .= "                value = narrow\n                return\n            }\n        }\n        fail\n    }\n\n";
            next;
        }
        my ($low, $high);
        my $limit = $tsigned ? $tbits - 1 : $tbits;
        my $two = sprintf('%.0f', 2 ** $limit) . '.0';
        my $fits = !defined $max || 2 ** $limit <= 65504;
        if ($tsigned) {
            $low = $fits ? "\@f_greater_than_or_equal_$s(self.data, -$two)" : "\@f_greater_than_or_equal_$s(self.data, -$max)";
        } else {
            $low = "\@f_greater_than_or_equal_$s(self.data, 0.0)";
        }
        $high = $fits ? "\@f_less_than_$s(self.data, $two)" : "\@f_less_than_or_equal_$s(self.data, $max)";
        $text .= "        if $low and $high and \@f_trunc_$s(self.data) == self.data {\n";
        $text .= "            value = $conv(self.data) as $tc\n            return\n        }\n        fail\n    }\n\n";
    }
    $text =~ s/\n\n$/\n/;
    $text .= "}\n";
    return $text;
}

for my $t (@ints) {
    my $file = "$out/" . lc($t->[0]) . ".lilac";
    open my $fh, '>', $file or die "$file: $!";
    print $fh $header, int_file($t);
    close $fh;
}
for my $f (@floats) {
    my $file = "$out/" . lc($f->[0]) . ".lilac";
    open my $fh, '>', $file or die "$file: $!";
    print $fh $header, float_file($f);
    close $fh;
}
