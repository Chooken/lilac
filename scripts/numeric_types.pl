                . "    // takes this type's width: `x * 2.0`, `1.0 < x`.\n";
        }
        for my $op (qw(add sub mul div mod)) {
            $text .= "    \@$op: function (lhs: $l, rhs: $r) $name => $name { data = \@f_$op\_$s($a, $b) }\n";
        }
        $text .= "\n";
        for my $op (@compare) {
            $text .= "    \@$op: function (lhs: $l, rhs: $r) Bool => \@f_$op\_$s($a, $b)\n";
        }
        $text .= "\n";
