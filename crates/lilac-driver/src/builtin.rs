//! The `@builtin` namespace: the target and build facts as Lilac source.
//!
//! The driver generates three namespaces from the session and appends them to
//! every loaded project: `@builtin` (the `Os`, `Arch` and `Mode` enums),
//! `@builtin.Target` and `@builtin.Build` (inline constants). They go through
//! the ordinary resolver and checker; code names them qualified
//! (`@builtin.Target.os`), and a `match` or `if` on one compiles only its live
//! arm (SPEC "Constant conditions"). Their files are named `<builtin>`.

use std::fmt::Write as _;
use std::path::PathBuf;

use lilac_ir::Entry;
use lilac_module::{FileUnit, Namespace, Project};
use lilac_span::SourceMap;
use lilac_target::{Arch, Os, Target};

use crate::OptimizeMode;

/// The display path of every generated file.
pub const BUILTIN_FILE: &str = "<builtin>";

/// The facts the `@builtin` namespace states.
#[derive(Clone, Copy, Debug)]
pub struct Facts {
    /// The compilation target.
    pub target: Target,
    /// How the program enters (`CMain` means the C library is linked).
    pub entry: Entry,
    /// The optimization mode.
    pub mode: OptimizeMode,
}

/// The generated sources, as `(namespace path, source)` pairs.
#[must_use]
pub fn sources(facts: Facts) -> [(&'static str, String); 3] {
    let Facts {
        target,
        entry,
        mode,
    } = facts;
    let mut types = String::from("// Generated by the compiler.\n\nOs: either {\n");
    for os in [Os::Windows, Os::Linux, Os::Macos, Os::None] {
        let _ = writeln!(types, "    {}", os.builtin_name());
    }
    types.push_str("}\n\nArch: either {\n");
    for arch in Arch::ALL {
        let _ = writeln!(types, "    {}", arch.builtin_name());
    }
    types.push_str("}\n\nMode: either {\n    Debug\n    Release\n    ReleaseSmall\n}\n");

    let libc = u8::from(entry == Entry::CMain || target.os == Os::Macos);
    let target_src = format!(
        "// Generated by the compiler.\n\n\
         os: Os => .{}\n\
         arch: Arch => .{}\n\
         pointer_size: @bit_native => 0x{:x}\n\
         page_size: @bit_native => 0x{:x}\n\
         libc: @bit8 => 0x{libc:x}\n",
        target.os.builtin_name(),
        target.arch.builtin_name(),
        target.bit_native_width() / 8,
        target.page_size(),
    );
    let mode = match mode {
        OptimizeMode::Debug => "Debug",
        OptimizeMode::Release => "Release",
        OptimizeMode::ReleaseSmall => "ReleaseSmall",
    };
    let build_src = format!("// Generated by the compiler.\n\nmode: Mode => .{mode}\n");
    [
        ("@builtin", types),
        ("@builtin.Target", target_src),
        ("@builtin.Build", build_src),
    ]
}

/// `project` plus the `@builtin` namespaces, registered in `sources`.
#[must_use]
pub fn with_builtin(project: &Project, facts: Facts, sources_map: &mut SourceMap) -> Project {
    let mut project = project.clone();
    for (path, src) in sources(facts) {
        let file = sources_map.add_file(BUILTIN_FILE, &src);
        project.namespaces.push(Namespace {
            path: path.to_owned(),
            dir: PathBuf::from(BUILTIN_FILE),
            files: vec![project.files.len()],
        });
        project.files.push(FileUnit {
            name: BUILTIN_FILE.to_owned(),
            path: PathBuf::from(BUILTIN_FILE),
            file,
            ns: project.namespaces.len() - 1,
            src,
            usings: Vec::new(),
        });
    }
    project
}
