"""Generates lib/Standard/float_tables.lilac: the constants, lookup tables
and polynomial evaluators the elementary-function kernels use.

    python tools/math-reference/gen_kernels.py lib/Standard/float_tables.lilac

Every number is computed here with exact rationals and the `decimal`
module (see reference.py), split into double-double (hi, lo) pairs, and
printed as a shortest round-trip literal, so the Lilac compiler reads back
exactly the same doubles. The polynomial evaluators are unrolled Horner
schemes whose low-order tail (the terms too small to need double-double)
runs in plain `Float64`.
"""
import sys
from decimal import Decimal, localcontext
from fractions import Fraction
import math

import reference as R

PREC = 140


def lit(x):
    """A Float64 literal for the double x."""
    s = repr(float(x))
    s = s.replace('e+', 'e')
    if 'e' not in s and '.' not in s:
        s += '.0'
    if s in ('inf', '-inf', 'nan'):
        raise ValueError(s)
    return s


def to_frac(d):
    return Fraction(d)


def split(v, parts=2):
    """v (Fraction) as a sum of `parts` doubles."""
    out = []
    rest = Fraction(v)
    for _ in range(parts):
        d = float(rest)
        out.append(d)
        rest -= Fraction(d)
    return out


def dd(v):
    hi, lo = split(v, 2)
    return f"Dd.new({lit(hi)}, {lit(lo)})"


def dec_const(f):
    with localcontext() as c:
        c.prec = PREC
        return Fraction(f())


def ln2():
    with localcontext() as c:
        c.prec = PREC
        return Fraction(Decimal(2).ln())


def ln10():
    with localcontext() as c:
        c.prec = PREC
        return Fraction(Decimal(10).ln())


def pi():
    return Fraction(R.pi(PREC))


def sqrt_pi():
    with localcontext() as c:
        c.prec = PREC
        return Fraction(R.pi(PREC + 5).sqrt())


def sqrt_c(n):
    with localcontext() as c:
        c.prec = PREC
        return Fraction(Decimal(n).sqrt())


out = []


def emit(s=''):
    out.append(s)


def const(name, v, doc):
    emit(f"    /// {doc}")
    emit(f"    {name}: Dd => {dd(v)}")
    emit()


def fconst(name, v, doc):
    emit(f"    /// {doc}")
    emit(f"    {name}: Float64 => {lit(float(v))}")
    emit()


def horner(name, doc, coeffs, zmax, lead_power, arg='z', tail_start=None):
    """Emits `name: function (z: Dd) Dd` evaluating sum coeffs[i] z^i, with
    the terms from index i0 on in plain Float64."""
    n = len(coeffs)
    i0 = n
    for i in range(n):
        bound = 2.0 ** -53 * abs(float(coeffs[i])) * zmax ** (i + lead_power)
        if bound < 2.0 ** -112:
            i0 = i
            break
    if tail_start is not None:
        i0 = tail_start
    emit(f"    /// {doc}")
    emit(f"    {name}: function ({arg}: Dd) res: Dd {{")
    if i0 >= n:
        emit(f"        res = {dd(coeffs[n - 1])}")
        start = n - 2
    else:
        emit(f"        t: Float64 = {lit(float(coeffs[n - 1]))}")
        for i in range(n - 2, i0 - 1, -1):
            emit(f"        t = t * {arg}.hi + {lit(float(coeffs[i]))}")
        emit(f"        res = Dd.of(t)")
        start = i0 - 1
    for i in range(start, -1, -1):
        emit(f"        res = res * {arg} + {dd(coeffs[i])}")
    emit(f"    }}")
    emit()


def degree_for(coef_fn, zmax, lead_power, bits=114):
    """Smallest M so that term M is below 2^-bits relative to the lead."""
    m = 1
    while True:
        c = coef_fn(m)
        if 2.0 ** -53 * 0 + abs(float(c)) * zmax ** (m + lead_power) < 2.0 ** -bits:
            return m
        m += 1


def factorial(n):
    return math.factorial(n)


emit("// Generated by tools/math-reference/gen_kernels.py: edit that and rerun it.")
emit("//")
emit("// Constants, lookup tables and polynomial evaluators for the elementary")
emit("// functions (math plan phase 5). Numbers are double-double (`Dd`) pairs")
emit("// computed with exact rationals; tables are globals read through an array")
emit("// view; evaluators are unrolled Horner schemes.")
emit()
emit("private {")

# ---- constants -------------------------------------------------------------
L2 = ln2()
L10 = ln10()
PI = pi()
const('LN_2', L2, "`ln 2`.")
const('LN_10', L10, "`ln 10`.")
const('LOG2_E', 1 / L2, "`log2 e`.")
const('LOG10_E', 1 / L10, "`log10 e`.")
const('LOG10_2', L2 / L10, "`log10 2`.")
const('LOG2_10', L10 / L2, "`log2 10`.")
const('PI', PI, "`π`.")
const('PI_2', PI / 2, "`π / 2`.")
const('PI_4', PI / 4, "`π / 4`.")
const('TWO_OVER_PI', 2 / PI, "`2 / π`.")
const('SQRT_PI', sqrt_pi(), "`√π`.")
const('TWO_OVER_SQRT_PI', 2 / sqrt_pi(), "`2 / √π`.")
l1, l2, l3 = split(L2, 3)
fconst('LN_2_PART_1', l1, "`ln 2` as three doubles: the first part, ...")
fconst('LN_2_PART_2', l2, "... the second ...")
fconst('LN_2_PART_3', l3, "... and the third.")
p1, p2, p3 = split(PI / 2, 3)
fconst('PI_2_PART_1', p1, "`π / 2` as three doubles: the first part, ...")
fconst('PI_2_PART_2', p2, "... the second ...")
fconst('PI_2_PART_3', p3, "... and the third.")

# ---- exp: e^r - 1 = r * sum r^i / (i+1)! for |r| <= ln2/2 ---------------------
zmax = 0.3466
M = degree_for(lambda m: Fraction(1, factorial(m + 1)), zmax, 1)
horner('expm1_poly', "`(e^r - 1) / r` for `|r| <= ln 2 / 2` as a polynomial in `r`.",
       [Fraction(1, factorial(i + 1)) for i in range(M + 1)], zmax, 1)

# ---- log: ln(1+f) = 2s (1 + z W(z)), s = f / (2 + f), z = s^2 -------------------
zmax_log = (0.0175 / 2) ** 2 * 1.05
M = degree_for(lambda m: Fraction(1, 2 * m + 3), zmax_log, 1)
horner('log_poly', "`(ln((1 + s) / (1 - s)) / (2 s) - 1) / z` for small `s`, `z = s^2`, as a polynomial in `z`.",
       [Fraction(1, 2 * i + 3) for i in range(M + 1)], zmax_log, 1)

# the log table: j = 45..90, c = round(8192 / j) / 128, T = -ln(c)
LOG_FIRST, LOG_LAST = 45, 90
rows = []
for j in range(LOG_FIRST, LOG_LAST + 1):
    c = Fraction(round(Fraction(8192, j)), 128)
    t = -R.ln_(c) if c != 1 else Fraction(0)
    t = Fraction(t)
    th, tl = split(t, 2)
    rows.append((float(c), th, tl))
emit("    /// The log table: for `m` near `j / 64`, the entries `c`, `-ln c` high and `-ln c` low")
emit("    /// of entry `j - 45`, with `c` a multiple of 2^-7 near `64 / j`.")
emit("    LogTable: object {")
for i, (c, th, tl) in enumerate(rows):
    emit(f"        c{i}: Float64")
    emit(f"        h{i}: Float64")
    emit(f"        l{i}: Float64")
emit("    }")
emit()
emit("    log_table: LogTable = LogTable {")
for i, (c, th, tl) in enumerate(rows):
    emit(f"        c{i} = {lit(c)}, h{i} = {lit(th)}, l{i} = {lit(tl)}" + ("," if i + 1 < len(rows) else ""))
emit("    }")
emit()
emit(f"    LOG_TABLE_FIRST: Int32 => {LOG_FIRST}")
emit(f"    LOG_TABLE_LAST: Int32 => {LOG_LAST}")
emit()
emit("    /// Entry `index` (0-based) of the log table: `c`, then `-ln c` as a `Dd`.")
emit("    log_table_entry: function (index: Int32) (c: Float64, t: Dd) {")
emit("        view: ref @array(@fbit64, " + str(3 * len(rows)) + ") = (ref log_table) as ref unknown as ref @array(@fbit64, " + str(3 * len(rows)) + ")")
emit("        base: @bit_native = (index * 3).to_uint_wrapping() as @bit_native")
emit("        raw_c: @fbit64 = @array_at(view, base)")
emit("        raw_h: @fbit64 = @array_at(view, @i_add_native(base, 0x1))")
emit("        raw_l: @fbit64 = @array_at(view, @i_add_native(base, 0x2))")
emit("        c = raw_c as Float64")
emit("        t = Dd.new(raw_h as Float64, raw_l as Float64)")
emit("    }")
emit()


# ---- sin and cos: sin t = t + t z Qs(z), cos t = 1 + z Qc(z), z = t^2 --------------
zmax_trig = 0.6170
M = degree_for(lambda m: Fraction(1, factorial(2 * m + 3)), zmax_trig, 1)
horner('sin_poly', "`(sin t - t) / (t z)` for `|t| <= pi / 4 + eps`, `z = t^2`, as a polynomial in `z`.",
       [Fraction((-1) ** (i + 1), factorial(2 * i + 3)) for i in range(M + 1)], zmax_trig, 1)
M = degree_for(lambda m: Fraction(1, factorial(2 * m + 2)), zmax_trig, 1)
horner('cos_poly', "`(cos t - 1) / z` for `|t| <= pi / 4 + eps`, `z = t^2`, as a polynomial in `z`.",
       [Fraction((-1) ** (i + 1), factorial(2 * i + 2)) for i in range(M + 1)], zmax_trig, 1)

# ---- the bits of 2/pi for Payne-Hanek reduction ------------------------------------
WORDS = 24
with localcontext() as c:
    c.prec = 600
    two_pi = Fraction(2 / R.pi(600))
big = int(two_pi * (1 << (64 * WORDS)))
words = [(big >> (64 * (WORDS - 1 - i))) & ((1 << 64) - 1) for i in range(WORDS)]
emit("    /// The first 1536 bits of `2 / pi` after the binary point, 64 to a field.")
emit("    TwoOverPi: object {")
for i in range(WORDS):
    emit(f"        w{i}: @bit64")
emit("    }")
emit()
emit("    two_over_pi: TwoOverPi = TwoOverPi {")
for i, w in enumerate(words):
    emit(f"        w{i} = 0x{w:016X}" + ("," if i + 1 < WORDS else ""))
emit("    }")
emit()
emit("    /// Word `index` (0-based) of `2 / pi`'s bits.")
emit("    two_over_pi_word: function (index: @bit_native) res: @bit64 {")
emit(f"        view: ref @array(@bit64, {WORDS}) = (ref two_over_pi) as ref unknown as ref @array(@bit64, {WORDS})")
emit("        res = @array_at(view, index)")
emit("    }")
emit()


# ---- atan: atan(w) = w + w z R(z), z = w^2, |w| <= 1/128 ----------------------------
zmax_atan = (1 / 120.0) ** 2
M = degree_for(lambda m: Fraction(1, 2 * m + 3), zmax_atan, 1)
horner('atan_poly', "`(atan w - w) / (w z)` for `|w| <= 1/120`, `z = w^2`, as a polynomial in `z`.",
       [Fraction((-1) ** (i + 1), 2 * i + 3) for i in range(M + 1)], zmax_atan, 1)
rows = []
for j in range(0, 65):
    v = Fraction(R.atan_(Fraction(j, 64))) if j else Fraction(0)
    rows.append(split(v, 2))
emit("    /// `atan(j / 64)` for `j` in 0..=64, as (high, low) pairs.")
emit("    AtanTable: object {")
for i in range(len(rows)):
    emit(f"        h{i}: Float64")
    emit(f"        l{i}: Float64")
emit("    }")
emit()
emit("    atan_table: AtanTable = AtanTable {")
for i, (h, l) in enumerate(rows):
    emit(f"        h{i} = {lit(h)}, l{i} = {lit(l)}" + ("," if i + 1 < len(rows) else ""))
emit("    }")
emit()
emit("    /// `atan(j / 64)`.")
emit("    atan_table_entry: function (j: Int32) res: Dd {")
emit(f"        view: ref @array(@fbit64, {2 * len(rows)}) = (ref atan_table) as ref unknown as ref @array(@fbit64, {2 * len(rows)})")
emit("        base: @bit_native = (j * 2).to_uint_wrapping() as @bit_native")
emit("        raw_h: @fbit64 = @array_at(view, base)")
emit("        raw_l: @fbit64 = @array_at(view, @i_add_native(base, 0x1))")
emit("        res = Dd.new(raw_h as Float64, raw_l as Float64)")
emit("    }")
emit()


# ---- gamma: Stirling's series and the expansion of ln Gamma(1 + t) -----------------
from decimal import Decimal, getcontext

STIRLING_FROM = 20


def stirling_coefficient(k):
    return Fraction(R.bernoulli(2 * k)) / (2 * k * (2 * k - 1))


zmax_stirling = 1.0 / (STIRLING_FROM * STIRLING_FROM)
K = 1
while abs(float(stirling_coefficient(K))) * zmax_stirling ** K / STIRLING_FROM > 2.0 ** -118:
    K += 1
horner('stirling_poly', "`sum B_2k / (2k (2k-1)) w^(k-1)` with `w = 1 / z^2`, for `z >= 20`; times `1/z` it is the correction of `ln Gamma(z)`.",
       [stirling_coefficient(k + 1) for k in range(K + 1)], zmax_stirling, 1)
const('HALF_LN_2PI', dec_const(lambda: (2 * R.pi(PREC + 5)).ln() / 2), "`ln(2 pi) / 2`.")
const('INV_SQRT_PI', 1 / sqrt_pi(), "`1 / sqrt(pi)`.")


def zeta(sv):
    """Riemann zeta at the integer sv >= 2 (Euler-Maclaurin), as a Fraction."""
    with localcontext() as c:
        c.prec = PREC + 20
        N = 70
        total = sum(Decimal(1) / Decimal(n) ** sv for n in range(1, N))
        Nd = Decimal(N)
        total += Nd ** (1 - sv) / (sv - 1) + Nd ** (-sv) / 2
        term_factor = Decimal(sv)
        j = 1
        rising = Decimal(sv)
        while j < 45:
            b = Decimal(R.bernoulli(2 * j).numerator) / Decimal(R.bernoulli(2 * j).denominator)
            total += b / math.factorial(2 * j) * rising * Nd ** (-sv - 2 * j + 1)
            rising *= (sv + 2 * j - 1) * (sv + 2 * j)
            j += 1
        return Fraction(total)


def euler_gamma():
    with localcontext() as c:
        c.prec = PREC + 20
        N = 200
        h = sum(Decimal(1) / n for n in range(1, N + 1))
        g = h - Decimal(N).ln() - Decimal(1) / (2 * N)
        for j in range(1, 40):
            b = Decimal(R.bernoulli(2 * j).numerator) / Decimal(R.bernoulli(2 * j).denominator)
            g += b / (2 * j * Decimal(N) ** (2 * j))
        return Fraction(g)


# ln Gamma(1 + t) = t (-gamma + sum_{k>=2} (-1)^k zeta(k) t^(k-1) / k)
zmax_lg = 0.2501
coefs = [-euler_gamma()]
k = 2
while True:
    c = Fraction((-1) ** k) * zeta(k) / k
    coefs.append(c)
    if abs(float(c)) * zmax_lg ** (k - 1) < 2.0 ** -118 and k > 8:
        break
    k += 1
horner('lgamma1_poly', "`ln Gamma(1 + t) / t` for `|t| <= 1/4` as a polynomial in `t`.", coefs, zmax_lg, 1)

emit("}")
