PREC = 140


def lit(x):
    """A Float64 literal for the double x."""
    s = repr(float(x))
    s = s.replace('e+', 'e')
    if 'e' not in s and '.' not in s:
        s += '.0'
    if s in ('inf', '-inf', 'nan'):
        raise ValueError(s)
    return s


def to_frac(d):
    return Fraction(d)


def split(v, parts=2):
    """v (Fraction) as a sum of `parts` doubles."""
    out = []
    rest = Fraction(v)
    for _ in range(parts):
        d = float(rest)
        out.append(d)
        rest -= Fraction(d)
    return out


def bits_of(v):
    """The significant bits of the double v."""
    f = Fraction(v)
    if f == 0:
        return 0
    n = f.numerator
    while n % 2 == 0:
        n //= 2
    return abs(n).bit_length()


def dd(v):
    hi, lo = split(v, 2)
    return f"Dd.new({lit(hi)}, {lit(lo)})"


def dec_const(f):
    with localcontext() as c:
        c.prec = PREC
        return Fraction(f())


def ln2():
    with localcontext() as c:
        c.prec = PREC
        return Fraction(Decimal(2).ln())


def ln10():
    with localcontext() as c:
        c.prec = PREC
        return Fraction(Decimal(10).ln())


def pi():
    return Fraction(R.pi(PREC))


def sqrt_pi():
    with localcontext() as c:
        c.prec = PREC
        return Fraction(R.pi(PREC + 5).sqrt())


def sqrt_c(n):
    with localcontext() as c:
        c.prec = PREC
        return Fraction(Decimal(n).sqrt())


