# ---- gamma: Stirling's series and the expansion of ln Gamma(1 + t) -----------------
from decimal import Decimal, getcontext

STIRLING_FROM = 20


def stirling_coefficient(k):
    return Fraction(R.bernoulli(2 * k)) / (2 * k * (2 * k - 1))


zmax_stirling = 1.0 / (STIRLING_FROM * STIRLING_FROM)
K = 1
while abs(float(stirling_coefficient(K))) * zmax_stirling ** K / STIRLING_FROM > 2.0 ** -118:
    K += 1
horner('stirling_poly', "`sum B_2k / (2k (2k-1)) w^(k-1)` with `w = 1 / z^2`, for `z >= 20`; times `1/z` it is the correction of `ln Gamma(z)`.",
       [stirling_coefficient(k + 1) for k in range(K + 1)], zmax_stirling, 1)
const('HALF_LN_2PI', dec_const(lambda: (2 * R.pi(PREC + 5)).ln() / 2), "`ln(2 pi) / 2`.")
const('INV_SQRT_PI', 1 / sqrt_pi(), "`1 / sqrt(pi)`.")


def zeta(sv):
    """Riemann zeta at the integer sv >= 2 (Euler-Maclaurin), as a Fraction."""
    with localcontext() as c:
        c.prec = PREC + 20
        N = 70
        total = sum(Decimal(1) / Decimal(n) ** sv for n in range(1, N))
        Nd = Decimal(N)
        total += Nd ** (1 - sv) / (sv - 1) + Nd ** (-sv) / 2
        term_factor = Decimal(sv)
        j = 1
        rising = Decimal(sv)
        while j < 45:
            b = Decimal(R.bernoulli(2 * j).numerator) / Decimal(R.bernoulli(2 * j).denominator)
            total += b / math.factorial(2 * j) * rising * Nd ** (-sv - 2 * j + 1)
            rising *= (sv + 2 * j - 1) * (sv + 2 * j)
            j += 1
        return Fraction(total)


def euler_gamma():
    with localcontext() as c:
        c.prec = PREC + 20
        N = 200
        h = sum(Decimal(1) / n for n in range(1, N + 1))
        g = h - Decimal(N).ln() - Decimal(1) / (2 * N)
        for j in range(1, 40):
            b = Decimal(R.bernoulli(2 * j).numerator) / Decimal(R.bernoulli(2 * j).denominator)
            g += b / (2 * j * Decimal(N) ** (2 * j))
        return Fraction(g)


# ln Gamma(1 + t) = t (-gamma + sum_{k>=2} (-1)^k zeta(k) t^(k-1) / k)
zmax_lg = 0.2501
coefs = [-euler_gamma()]
k = 2
while True:
    c = Fraction((-1) ** k) * zeta(k) / k
    coefs.append(c)
    if abs(float(c)) * zmax_lg ** (k - 1) < 2.0 ** -118 and k > 8:
        break
    k += 1
horner('lgamma1_poly', "`ln Gamma(1 + t) / t` for `|t| <= 1/4` as a polynomial in `t`.", coefs, zmax_lg, 1)

emit("}")
