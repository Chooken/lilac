"""Generates lib/Standard/float_tables.lilac: the constants, lookup tables
and polynomial evaluators the elementary-function kernels use.

    python tools/math-reference/gen_kernels.py lib/Standard/float_tables.lilac

Every number is computed here with exact rationals and the `decimal`
module (see reference.py), split into double-double (hi, lo) pairs, and
printed as a shortest round-trip literal, so the Lilac compiler reads back
exactly the same doubles. The polynomial evaluators are unrolled Horner
schemes whose low-order tail (the terms too small to need double-double)
runs in plain `Float64`.
"""
import sys
